"""Write the variant problems for the LEAP evaluation tasks: one scene, three binary factors.

Every cell is the same scene and goal. A two-block tower spells the last two letters of the word
(readable at o2) and the first letter lies loose on the table, not upright; the goal is the
three-block tower spelling the word from top to bottom with every letter at o2. The factors,
chosen so that the task types form a gradient:

- **region**: `feasible`, the loose block anywhere in `on_table`'s box, or `outside`, in one of
  the table regions beyond the flip/rotate training distribution (`near_robot`, `far_left`,
  `far_right`, cycling across variants; ToyBlocks's `predicates/in_region.py`). The factor
  is about the loose block: an outside family's loose block starts where
  rotate and flip decline, a feasible family's where they act, and the tower goes wherever
  adjacency puts it. So the loose block is what `in_region` places, in every outside cell.
- **proximity**: `isolated`, or `adjacent`, the tower's bottom block 2-3 cm beside the loose
  block (`predicates/near.py`), close enough that turning the loose block in place disturbs
  the tower. `near` places its first argument beside its second, so the tower is placed
  relative to the loose block, after `in_region` has placed that. Placing the loose block
  relative to the tower instead could land an outside cell's loose block on the tower's inner
  side, inside the band where rotate and flip act.
- **skill**: `rotate`, the loose block yawed (o1, o3 or o4, one or two rotates from o2, and a
  rotate leaves the gripper open), or `flip`, the loose block on its side (o6 or o14, the letter
  facing the camera but rolled, one left or right flip from o2) or letter face up (o21, one
  front flip from o2), and a flip leaves the gripper closed, which `pick`
  cannot recover from. The `flip`
  cells are the Gripper Preconditions test and are parked until the flip skill works
  (2026-09-29: it never turned a block in 36 attempts).

The variants of a family are its remaining factors crossed, nothing drawn: a feasible family has three variants, one per start orientation of its skill; an
outside family has nine, the three orientations by the three outside regions. Each variant's
package then samples its own reset states (32 by default, `agentic-robotics generate-env`), which is
where placement varies. So 12 feasible and 36 outside variants in all.

The word is spelled from the letters the checkpoint trained on, A, I, L, E, D and 2 (the
asset check compares library and scale, not glyphs, so this is on the generator); the default
is AI2, which every evaluation task spells. Predicates are
sampled in file order after `on_table`, so `in_region` and `near` come before `ori_of`, which
draws the orientation last.

    python examples/agent/task_gen/generate_leap_problems.py

writes every cell, `data/problems/stack_<region>_<proximity>_<skill>/<slug>_NN.pddl`; `--cells`
narrows it. Build one with `examples/agent/leap/render_task.py --pddl <file> --generate-env`,
or all of a cell with `agentic-robotics generate-env --task <cell>` once it is registered in `config.py`.
"""

from __future__ import annotations

import argparse
import itertools
from pathlib import Path

PROBLEMS_DIR = Path(__file__).resolve().parents[3] / "data/problems"

REGIONS = ("feasible", "outside")
PROXIMITIES = ("isolated", "adjacent")
SKILLS = ("rotate", "flip")
"""The reorientation skill the loose block's start orientation requires."""
OUTSIDE_REGIONS = ("near_robot", "far_left", "far_right")
"""`near_camera` is left out: the camera's frame ends inside the training distribution."""

TRAINED_LETTERS = "AILED2"
READABLE = "o2"
FLIPPED = ("o6", "o14", "o21")
"""One flip from o2: the letter facing the camera but rolled 90 degrees either way (o6 needs a
left flip, o14 a right flip), or the letter face up (o21, a front flip; the camera reads it from
above)."""
YAWED = ("o1", "o3", "o4")
"""Top face up but another face forward: one or two rotates from o2."""

LETTER_TYPE = "block_letter"
DIGIT_TYPE = "block_digit"

TEMPLATE = """(define (problem {slug})
    (:domain blocks-tamp)
    ; LEAP evaluation cell region={region} proximity={proximity} skill={skill}.
    ; Tower {tower_top} on {tower_bottom} at o2; loose block {loose} starts at {loose_ori}{extra}.
    ; Generated by examples/agent/task_gen/generate_leap_problems.py; regenerate rather than edit.
    (:objects
{objects}
    workspace_table - table
    robot - gripper    )
    (:init
        (on_table {tower_bottom} workspace_table)
        (on_table {loose} workspace_table)
{placement}
        (on {tower_top} {tower_bottom})

        (clear {tower_top})
        (clear {loose})

        (handempty robot)

        (ori_of {tower_bottom} o2)
        (ori_of {tower_top} o2)
        (ori_of {loose} {loose_ori})

        (gripper_at_init)
    )
    (:goal (and
        (on {loose} {tower_top})
        (on {tower_top} {tower_bottom})
        (ori_of {loose} o2)
        (ori_of {tower_top} o2)
        (ori_of {tower_bottom} o2)
    ))
)
"""


def cell_slug(region: str, proximity: str, skill: str) -> str:
    """The task slug of one cell, also its problem directory."""
    return f"stack_{region}_{proximity}_{skill}"


def variants(region: str, skill: str) -> list[tuple[str, str | None]]:
    """The (orientation, outside region) of every variant of a family, in index order.

    A feasible family crosses its skill's orientations with nothing; an outside family crosses
    them with the outside regions, orientation-major, so variant NN is orientation NN // 3 and
    region NN % 3.
    """
    orientations = YAWED if skill == "rotate" else FLIPPED
    if region == "feasible":
        return [(o, None) for o in orientations]
    return [(o, a) for o in orientations for a in OUTSIDE_REGIONS]


def render(
    slug: str,
    region: str,
    proximity: str,
    skill: str,
    word: str,
    loose_ori: str,
    area: str | None,
) -> str:
    """The PDDL text of one variant.

    :param slug: Problem name, also the file stem and the autogen package slug
    :param region: `feasible` or `outside`
    :param proximity: `isolated` or `adjacent`
    :param skill: `rotate` or `flip`, the reorientation the start orientation requires
    :param word: Three distinct trained glyphs, top to bottom
    :param loose_ori: The loose block's start orientation
    :param area: The outside region, in an outside family; None in a feasible one
    """
    loose, tower_top, tower_bottom = (f"block_{c.lower()}" for c in word)
    types = {
        b: (DIGIT_TYPE if b[-1].isdigit() else LETTER_TYPE)
        for b in (loose, tower_top, tower_bottom)
    }
    placement: list[str] = []
    extra: list[str] = []
    if region == "outside":
        assert area is not None
        placement.append(f"        (in_region {loose} {area})")
        extra.append(f" in region {area}")
    if proximity == "adjacent":
        # `near` runs after `in_region` and places its first argument beside its second: the
        # tower's bottom block goes beside the already-placed loose block, and `on` then puts
        # the tower's top block on it.
        placement.append(f"        (near {tower_bottom} {loose})")
        extra.append(f"; {tower_bottom} 2-3 cm beside it")
    return TEMPLATE.format(
        slug=slug,
        region=region,
        proximity=proximity,
        skill=skill,
        tower_top=tower_top,
        tower_bottom=tower_bottom,
        loose=loose,
        loose_ori=loose_ori,
        extra="".join(extra),
        objects="\n".join(f"    {b} - {t}" for b, t in types.items()),
        placement="\n".join(placement),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--word", default="AI2", help="Three distinct trained glyphs to spell, top to bottom"
    )
    parser.add_argument(
        "--cells",
        nargs="*",
        default=None,
        help="Cell slugs to write (default: all eight), e.g. stack_outside_isolated_rotate",
    )
    args = parser.parse_args()
    word = args.word.upper()
    if len(word) != 3 or len(set(word)) != 3 or any(c not in TRAINED_LETTERS for c in word):
        raise SystemExit(f"--word must be three distinct glyphs from {TRAINED_LETTERS}.")

    cells = [
        (r, p, s)
        for r, p, s in itertools.product(REGIONS, PROXIMITIES, SKILLS)
        if args.cells is None or cell_slug(r, p, s) in args.cells
    ]
    if not cells:
        raise SystemExit("No cell matched --cells.")
    for region, proximity, skill in cells:
        cell = cell_slug(region, proximity, skill)
        out_dir = PROBLEMS_DIR / cell
        out_dir.mkdir(parents=True, exist_ok=True)
        for stale in out_dir.glob("*.pddl"):
            stale.unlink()  # A family's variant count can change; leave no extras behind
        rows = variants(region, skill)
        for i, (loose_ori, area) in enumerate(rows):
            slug = f"{cell}_{i:02d}"
            (out_dir / f"{slug}.pddl").write_text(
                render(slug, region, proximity, skill, word, loose_ori, area)
            )
        print(f"{out_dir}: {len(rows)} variants")


if __name__ == "__main__":
    main()
