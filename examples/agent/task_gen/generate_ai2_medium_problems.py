"""Write the `ai2_medium` variant problems: the `ai2_easy` scene with each block's start orientation drawn at random.

`ai2_easy` is A, I and 2 alone on the table, all starting at `o2`, so nothing has to be read or
turned. `ai2_medium` keeps that scene and drops the fixed start: each variant draws every block's
`ori_of` uniformly from the 24 resting orientations, so a block may start readable, sideways or
face-down, and the agent has to find out which. The goal is the same A-on-I-on-2 stack at `o2`.

Stage-1 codegen samples only the predicates a problem's `:init` names; a block with no `ori_of`
fact keeps its spawn orientation, which is fixed rather than random. The only way to get a random
start under `data/problems/` is therefore a directory of variants, one `ori_of` triple each, from
which `agentic-robotics` draws one per episode -- the same shape as `data/problems/ai2_stacked/`.

`generate_letter_color_problem.py` beside this file is not used because it types glyph blocks as
the generic `block_letter` and `block_2` as a plain `block`, and adds random stacking; the
`ai2_*` problems use the specific `block_a_n`, `block_i_v` and `block_2_6` types, and this task
should differ from `ai2_easy` in orientation only.

    python examples/agent/task_gen/generate_ai2_medium_problems.py --count 10 --seed 0

writes `data/problems/ai2_medium/ai2_medium_00.pddl` .. `_09.pddl`. Build them with
`agentic-robotics generate-env --task ai2_medium`.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

PROBLEMS_DIR = Path(__file__).resolve().parents[3] / "data/problems"

BLOCKS = [("block_a", "block_a_n"), ("block_i", "block_i_v"), ("block_2", "block_2_6")]
ORIENTATIONS = [f"o{i}" for i in range(1, 25)]

TEMPLATE = """(define (problem {slug})
    (:domain blocks-tamp)
    ; The Ai2 stack with only A, I and 2 on the table and no distractors, as in ai2_easy, but each
    ; block starts at an orientation drawn at random over o1..o24 (this variant: {oris}). Face five
    ; carries a block's named glyph and is forward only at o2, o6, o10 and o14, so a block may or
    ; may not start readable, and may need turning before it is stacked at o2.
    ; Generated by examples/agent/task_gen/generate_ai2_medium_problems.py; regenerate rather than edit.
    (:objects
{objects}
    workspace_table - table
    robot - gripper    )
    (:init
{on_table}

{clear}

        (handempty robot)

{ori_of}

        (gripper_at_init)
    )
    (:goal (and
        (on block_a block_i)
        (on block_i block_2)
        (ori_of block_a o2)
        (ori_of block_i o2)
        (ori_of block_2 o2)
    ))
)
"""


def render(slug: str, orientations: dict[str, str]) -> str:
    """The PDDL text of one variant.

    :param slug: Problem name, also the file stem and the autogen package slug
    :param orientations: Start orientation per block name
    """
    return TEMPLATE.format(
        slug=slug,
        oris=", ".join(f"{b} {orientations[b]}" for b, _ in BLOCKS),
        objects="\n".join(f"    {b} - {t}" for b, t in BLOCKS),
        on_table="\n".join(f"        (on_table {b} workspace_table)" for b, _ in BLOCKS),
        clear="\n".join(f"        (clear {b})" for b, _ in BLOCKS),
        ori_of="\n".join(f"        (ori_of {b} {orientations[b]})" for b, _ in BLOCKS),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--count", type=int, default=10, help="Variants to write")
    parser.add_argument("--seed", type=int, default=0, help="Seed for the orientation draws")
    parser.add_argument(
        "--task", default="ai2_medium", help="Task slug; variants go under data/problems/<task>/"
    )
    args = parser.parse_args()

    rng = random.Random(args.seed)
    out_dir = PROBLEMS_DIR / args.task
    out_dir.mkdir(parents=True, exist_ok=True)
    for i in range(args.count):
        slug = f"{args.task}_{i:02d}"
        orientations = {b: rng.choice(ORIENTATIONS) for b, _ in BLOCKS}
        path = out_dir / f"{slug}.pddl"
        path.write_text(render(slug, orientations))
        print(f"{path}: {' '.join(orientations[b] for b, _ in BLOCKS)}")


if __name__ == "__main__":
    main()
